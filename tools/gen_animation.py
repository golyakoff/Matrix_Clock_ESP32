#!/usr/bin/env python3
"""Generate a Day Splash animation header from a GIF.

Reads a (nominally 64x32) GIF, coalesces its frames onto a black background,
packs every pixel into RGB565 and emits a C header under include/animations/,
then regenerates the include/animations.h registry from a small
JSON manifest so newly added animations get picked up automatically.

On ESP32 `const` data is memory-mapped from flash and directly addressable, so
the arrays are plain `const uint16_t[]` (no PROGMEM / pgm_read_* needed).

An animation can be restricted to the bigger boards with --min-flash-mb 16: the
registry then wraps both its #include and its table entry in
`#if MC_FLASH_MB >= 16` (MC_FLASH_MB comes from CONFIG_MC_FLASH_MB, set per build
variant in variants/*.defaults),
so its pixel data never reaches the 4MB binary. Gated animations are always
emitted last, which keeps the 4MB set a prefix of the 16MB set - the animation
index is stored in the RTC and sent over BLE, so it has to mean the same thing
on both builds.

Usage:
    python tools/gen_animation.py img/nyan_64x32.gif nyancat --name "Nyan Cat"
    python tools/gen_animation.py img/minions_64x32.gif minions --name "Minions" --min-flash-mb 16

Requires Pillow:  python -m pip install pillow
"""

import argparse
import json
import os
import re
import sys

from PIL import Image, ImageSequence

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANIM_DIR = os.path.join(REPO_ROOT, "include", "animations")       # per-animation headers
REGISTRY_PATH = os.path.join(REPO_ROOT, "include", "animations.h")  # registry, one level up
MANIFEST = os.path.join(REPO_ROOT, "tools", "animations_manifest.json")

# The firmware panel size. Frames are validated against this.
PANEL_W = 64
PANEL_H = 32

# The animation index travels in 4 bits (BLE byte 0 bits4..6 + byte 1 bit0 / RTC byte 0Ah
# bits4..7), so 16 is the ceiling.
MAX_ANIMATIONS = 16


def rgb565(r, g, b):
    """Pack 8-8-8 RGB into a 16-bit 5-6-5 value (matches Adafruit color565)."""
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def load_frames(gif_path):
    """Return (width, height, [ (rgb565_list, duration_ms), ... ]).

    Frames are coalesced over an opaque black background so partial frames and
    transparency both resolve to concrete pixels (transparent -> black = LED off).
    """
    im = Image.open(gif_path)
    width, height = im.size
    canvas = Image.new("RGBA", (width, height), (0, 0, 0, 255))
    frames = []
    for frame in ImageSequence.Iterator(im):
        canvas.alpha_composite(frame.convert("RGBA"))
        raw = canvas.convert("RGB").tobytes()
        packed = [rgb565(raw[i], raw[i + 1], raw[i + 2]) for i in range(0, len(raw), 3)]
        duration = int(frame.info.get("duration", 100) or 100)
        frames.append((packed, duration))
    return width, height, frames


def write_animation_header(slug, width, height, frames):
    prefix = slug.upper()
    path = os.path.join(ANIM_DIR, slug + ".h")
    n = len(frames)
    lines = []
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <Arduino.h>")
    lines.append("")
    lines.append(f"// Auto-generated by tools/gen_animation.py - do not edit by hand.")
    lines.append(f"// RGB565, {n} frame(s), {width}x{height}. On ESP32 this const data lives in")
    lines.append(f"// flash and is read by direct indexing (no PROGMEM / pgm_read_* needed).")
    lines.append("")
    lines.append(f"#define {prefix}_WIDTH  {width}")
    lines.append(f"#define {prefix}_HEIGHT {height}")
    lines.append(f"#define {prefix}_FRAME_COUNT {n}")
    lines.append("")
    lines.append(f"const uint16_t {prefix}_FRAMES[{prefix}_FRAME_COUNT * {prefix}_WIDTH * {prefix}_HEIGHT] = {{")
    for fi, (packed, _dur) in enumerate(frames):
        lines.append(f"    // frame {fi}")
        row = []
        for i, v in enumerate(packed):
            row.append(f"0x{v:04X},")
            if len(row) == 12:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
    lines.append("};")
    lines.append("")
    durations = ", ".join(str(d) for (_p, d) in frames)
    lines.append(f"const uint16_t {prefix}_FRAME_MS[{prefix}_FRAME_COUNT] = {{ {durations} }};")
    lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    return path


def load_manifest():
    if os.path.exists(MANIFEST):
        with open(MANIFEST, "r", encoding="utf-8") as f:
            manifest = json.load(f)
        for entry in manifest["animations"]:
            entry.setdefault("min_flash_mb", 4)  # written before gating existed
        return manifest
    return {"animations": []}


def save_manifest(manifest):
    with open(MANIFEST, "w", newline="\n", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")


def upsert_manifest(manifest, slug, name, source, min_flash_mb):
    for entry in manifest["animations"]:
        if entry["slug"] == slug:
            entry["name"] = name
            entry["source"] = source
            entry["min_flash_mb"] = min_flash_mb
            return
    manifest["animations"].append(
        {"slug": slug, "name": name, "source": source, "min_flash_mb": min_flash_mb}
    )


def guard_open(entry):
    mb = entry.get("min_flash_mb", 4)
    return [f"#if MC_FLASH_MB >= {mb}"] if mb > 4 else []


def guard_close(entry):
    return ["#endif"] if entry.get("min_flash_mb", 4) > 4 else []


def registry_order(manifest):
    """Manifest order, but with the flash-gated animations moved to the end.

    Defines the animation index, so the unconditional animations must keep the
    low indices: that makes the 4MB set a prefix of the 16MB set.
    """
    entries = manifest["animations"]
    return sorted(entries, key=lambda e: e.get("min_flash_mb", 4))


def write_registry(manifest):
    entries = registry_order(manifest)
    path = REGISTRY_PATH
    lines = []
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <Arduino.h>")
    lines.append("")
    lines.append("// Auto-generated by tools/gen_animation.py - do not edit by hand.")
    lines.append("// Registry of Day Splash animations. Include this header from exactly one")
    lines.append("// translation unit (matrix.cpp): the per-animation headers define the pixel")
    lines.append("// arrays with external linkage, so including it twice would break the link.")
    lines.append("")
    lines.append("// Board flash size in MB, set per build variant (CONFIG_MC_FLASH_MB in")
    lines.append("// variants/*.defaults). Animations that only fit the bigger boards are gated")
    lines.append("// on it; assume the small board when it is missing so an ungated build still links.")
    lines.append("#ifdef CONFIG_MC_FLASH_MB")
    lines.append("#define MC_FLASH_MB CONFIG_MC_FLASH_MB")
    lines.append("#else")
    lines.append("#define MC_FLASH_MB 4")
    lines.append("#endif")
    lines.append("")
    for entry in entries:
        lines.extend(guard_open(entry))
        lines.append(f'#include "animations/{entry["slug"]}.h"')
        lines.extend(guard_close(entry))
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    const char*     name;        // human-readable label (for the app/debug)")
    lines.append("    uint8_t         width;")
    lines.append("    uint8_t         height;")
    lines.append("    uint8_t         frame_count;")
    lines.append("    const uint16_t* frames;      // frame_count * width * height RGB565 words")
    lines.append("    const uint16_t* frame_ms;    // per-frame duration in ms, frame_count entries")
    lines.append("} animation_t;")
    lines.append("")
    lines.append("static const animation_t ANIMATIONS[] = {")
    for entry in entries:
        p = entry["slug"].upper()
        lines.extend(guard_open(entry))
        lines.append(
            f'    {{ "{entry["name"]}", {p}_WIDTH, {p}_HEIGHT, {p}_FRAME_COUNT, {p}_FRAMES, {p}_FRAME_MS }},'
        )
        lines.extend(guard_close(entry))
    lines.append("};")
    lines.append("")
    lines.append("// Counted from the table so the gated entries above simply drop out of it.")
    lines.append("#define ANIMATION_COUNT ((uint8_t)(sizeof(ANIMATIONS) / sizeof(ANIMATIONS[0])))")
    lines.append("")
    lines.append("// Returns a valid animation for the given index, clamped into range.")
    lines.append("static inline const animation_t* animation_get(uint8_t index)")
    lines.append("{")
    lines.append("    if (index >= ANIMATION_COUNT)")
    lines.append("        index = 0;")
    lines.append("    return &ANIMATIONS[index];")
    lines.append("}")
    lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    return path


def main():
    ap = argparse.ArgumentParser(description="Generate a Day Splash animation header from a GIF.")
    ap.add_argument("gif", help="path to the source GIF (expected 64x32)")
    ap.add_argument("slug", help="lowercase identifier, e.g. 'nyancat' (used for the file and macro prefix)")
    ap.add_argument("--name", help="human-readable label; defaults to the slug")
    ap.add_argument("--min-flash-mb", type=int, choices=(4, 16), default=4,
                    help="smallest board this animation ships on (default 4 = every build)")
    args = ap.parse_args()

    if not re.fullmatch(r"[a-z][a-z0-9_]*", args.slug):
        sys.exit(f"error: slug '{args.slug}' must be lowercase [a-z0-9_], starting with a letter")

    name = args.name or args.slug
    os.makedirs(ANIM_DIR, exist_ok=True)

    width, height, frames = load_frames(args.gif)
    if (width, height) != (PANEL_W, PANEL_H):
        sys.exit(f"error: {args.gif} is {width}x{height}, expected {PANEL_W}x{PANEL_H}")
    if not frames:
        sys.exit(f"error: {args.gif} has no frames")
    if len(frames) > 255:
        sys.exit("error: frame_count must fit in a uint8_t (<= 255)")

    header = write_animation_header(args.slug, width, height, frames)

    manifest = load_manifest()
    upsert_manifest(manifest, args.slug, name,
                    os.path.relpath(args.gif, REPO_ROOT).replace("\\", "/"), args.min_flash_mb)
    if len(manifest["animations"]) > MAX_ANIMATIONS:
        sys.exit(f"error: {len(manifest['animations'])} animations, but the index is 3 bits "
                 f"(max {MAX_ANIMATIONS}) - drop one first")
    save_manifest(manifest)
    registry = write_registry(manifest)

    total_words = sum(len(p) for (p, _d) in frames)
    counts = {}
    for entry in manifest["animations"]:
        counts[entry.get("min_flash_mb", 4)] = counts.get(entry.get("min_flash_mb", 4), 0) + 1
    n_4mb = counts.get(4, 0)
    n_16mb = n_4mb + counts.get(16, 0)
    print(f"Wrote {os.path.relpath(header, REPO_ROOT)} "
          f"({len(frames)} frames, {total_words * 2} bytes of pixel data, "
          f"{args.min_flash_mb}MB boards and up)")
    print(f"Wrote {os.path.relpath(registry, REPO_ROOT)} "
          f"(ANIMATION_COUNT = {n_4mb} on 4MB, {n_16mb} on 16MB)")


if __name__ == "__main__":
    main()
